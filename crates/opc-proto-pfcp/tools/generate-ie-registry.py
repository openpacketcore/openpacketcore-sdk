#!/usr/bin/env python3
"""Generate the R19 IE registry from pdftotext -layout of TS 29.244 V19.6.0.

Source: https://www.etsi.org/deliver/etsi_ts/129200_129299/129244/19.06.00_60/ts_129244v190600p.pdf
Usage: python3 tools/generate-ie-registry.py /path/to/pfcp.txt [--check]
The generated registry describes assigned identifiers, not typed-value support.
"""
import argparse
from pathlib import Path
import re

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('source', type=Path)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
text = args.source.read_text()
assert '3GPP TS 29.244 version 19.6.0' in text
text = text[text.index('  IE Type value'):text.index('404 to 32767')]
rows = list(re.finditer(r'^\s*(\d+)\s+([^\n]*)', text, re.MULTILINE))
assert [int(row[1]) for row in rows] == list(range(404))
entries = []
for index, row in enumerate(rows):
    number = int(row[1])
    if number in (0, 116, 273, 381):
        assert re.search(r'Reserved|Spare|Can be used', row[2])
        continue
    end = rows[index + 1].start() if index + 1 < len(rows) else len(text)
    ref = re.search(r'(?:Clause|Table) (\d+(?:\.\d+)+(?:-\d+)?)', text[row.start():end])
    assert ref, number
    reference = ref[1]
    # Three table references omit a dot; verify the numbered clause headings.
    if number in (55, 56, 57):
        assert reference == '8.2'
        reference = f'8.2.{number - 20}'
        assert re.search(r'^' + re.escape(reference) + r'\s+', args.source.read_text(), re.MULTILINE)
    # The table prints 8.205; the actual clause heading is 8.2.205.
    if number == 299:
        assert reference == '8.205'
        assert re.search(r'^8\.2\.205\s+Predefined Rules Name', args.source.read_text(), re.MULTILINE)
        reference = '8.2.205'
    assert reference.count(".") >= 2, (number, reference)
    entries.append(f'    ({number}, "{reference}"),')
output = '''// Generated by tools/generate-ie-registry.py; do not edit by hand.
// TS 29.244 V19.6.0 Table 8.1.2-1. Reserved, spare and unassigned rows excluded.

/// Assigned IE types and their defining clause/table in TS 29.244 V19.6.0.
/// A registered identifier does not imply that this crate validates its value.
pub const IE_DEFINITIONS: &[(u16, &str)] = &[
''' + '\n'.join(entries) + '\n];\n'
path = Path(__file__).resolve().parents[1] / 'src/ie/registry.rs'
if args.check:
    assert path.read_text() == output, f'{path} is stale'
else:
    path.write_text(output)
print(f'{len(entries)} assigned IE definitions')
